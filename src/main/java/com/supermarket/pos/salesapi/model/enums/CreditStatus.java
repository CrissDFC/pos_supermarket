package com.supermarket.pos.salesapi.model.enums;

/**
 * Represents the credit approval status of a customer.
 */
public enum CreditStatus {
    /**
     * Customer credit has been approved
     */
    APPROVED,
    
    /**
     * Customer credit has been rejected
     */
    REJECTED,
    
    /**
     * Customer credit is pending approval
     */
    PENDING
}
